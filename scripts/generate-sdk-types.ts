/** Regenerate SDK aliases from the checked-in schemas. No schema evaluation or network access. */
import ts from 'typescript'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const header = '// Generated by bun scripts/generate-sdk-types.ts. Do not edit.\n'
export function generateSchemaAliases(source: string, module: string, core = false): string {
  const file = ts.createSourceFile('schemas.ts', source, ts.ScriptTarget.Latest, true)
  const declarations = file.statements.filter(ts.isVariableStatement).flatMap(statement =>
    statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
      ? [...statement.declarationList.declarations] : [])
    .filter(declaration => ts.isIdentifier(declaration.name) && declaration.name.text.endsWith('Schema'))
  const aliases = declarations.map(declaration => {
    const schema = declaration.name.getText(file)
    const name = schema.slice(0, -6)
    const text = declaration.initializer?.getText(file) ?? ''
    // Compose unions through exported aliases so external API placeholders stay typed.
    const union = text.match(/^lazySchema\(\(\) =>\s*z\.union\(\[([\s\S]*?)\]\),?\s*\)$/)
    let type = `z.output<ReturnType<typeof schemas.${schema}>>`
    if (union && /^\s*(?:\w+Schema\(\),?\s*)+$/.test(union[1]!)) {
      type = [...union[1]!.matchAll(/(\w+)Schema\(\)/g)].map(match => match[1]).join(' | ')
    }
    const external: Record<string, string> = {
      SDKUserMessage: 'message: APIUserMessage', SDKUserMessageReplay: 'message: APIUserMessage',
      SDKAssistantMessage: 'message: APIAssistantMessage', SDKPartialAssistantMessage: 'event: RawMessageStreamEvent',
      SDKResultSuccess: 'usage: NonNullableUsage', SDKResultError: 'usage: NonNullableUsage',
      SDKControlMcpMessageRequest: 'message: JSONRPCMessage',
    }
    if (name === 'SDKControlRequest') type = `Omit<${type}, 'request'> & { request: SDKControlRequestInner }`
    if (external[name]) {
      const property = external[name]!.split(':')[0]
      type = `Omit<${type}, '${property}'> & { ${external[name]} }`
    }
    return `export type ${name} = ${type}\n`
  }).join('')
  return header + `import type { z } from 'zod/v4'\nimport type * as schemas from '${module}'\n` +
    (core ? `import type { MessageParam as APIMessageParam } from '@anthropic-ai/sdk/resources/messages/messages.mjs'\nimport type { BetaMessage as APIAssistantMessage, BetaRawMessageStreamEvent as RawMessageStreamEvent } from '@anthropic-ai/sdk/resources/beta/messages/messages.mjs'\nimport type { NonNullableUsage } from './sdkUtilityTypes.js'\ntype APIUserMessage = APIMessageParam & { role: 'user' }\n` : `import type { JSONRPCMessage } from '@modelcontextprotocol/sdk/types.js'\nexport type { SDKPartialAssistantMessage } from './coreTypes.js'\nimport type { SDKMessage, SDKUserMessage, SDKStreamlinedTextMessage, SDKStreamlinedToolUseSummaryMessage, SDKPostTurnSummaryMessage } from './coreTypes.js'\n`) + '\n' + aliases
}
export async function generateSdkTypes(check = false): Promise<boolean> {
  const outputs = [
    ['src/entrypoints/sdk/coreTypes.generated.ts', generateSchemaAliases(await readFile(resolve(root, 'src/entrypoints/sdk/coreSchemas.ts'), 'utf8'), './coreSchemas.js', true)],
    ['src/entrypoints/sdk/controlTypes.ts', generateSchemaAliases(await readFile(resolve(root, 'src/entrypoints/sdk/controlSchemas.ts'), 'utf8'), './controlSchemas.js')],
    ['src/entrypoints/sdk/settingsTypes.generated.ts', header + "import type { SettingsJson } from '../../utils/settings/types.js'\nexport type Settings = SettingsJson\n"],
  ] as const
  let valid = true
  for (const [path, content] of outputs) {
    if (check) {
      if (await readFile(resolve(root, path), 'utf8').catch(() => '') !== content) {
        console.error(`SDK types out of date: ${path}`)
        valid = false
      }
    } else await writeFile(resolve(root, path), content)
  }
  return valid
}
if (import.meta.main && !await generateSdkTypes(process.argv.includes('--check'))) process.exitCode = 1
